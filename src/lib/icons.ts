export type McIconName = keyof typeof s16;

export function renderMcIcon(name: McIconName): React.ReactElement {
  const factory = s16[name];
  if (!factory) {
    return React.createElement('svg', {
      viewBox: '0 0 16 16', width: '100%', height: '100%',
      style: { imageRendering: 'pixelated', display: 'block' },
    }, r('#888', 0, 0, 16, 16), r('#F44', 4, 4, 8, 8));
  }
  return factory();
}

