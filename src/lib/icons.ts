import React from 'react';

function r(color: string, x: number, y: number, w = 1, h = 1) {
  return React.createElement('rect', {
    key: `${x}-${y}`,
    x, y, width: w, height: h,
    fill: color,
    shapeRendering: 'crispEdges' as any,
  });
}

function pixelIcon(size: number, elements: [string, number, number, number?, number?][]): React.ReactElement {
  return React.createElement('svg', {
    key: Math.random().toString(36).slice(2),
    viewBox: `0 0 ${size} ${size}`,
    width: '100%', height: '100%',
    style: { imageRendering: 'pixelated', display: 'block' },
  }, ...elements.map(([c, x, y, w = 1, h = 1]) => r(c, x, y, w, h)));
}

function makeIcon(size: number, pixels: [string, number, number, number?, number?][]) {
  return () => pixelIcon(size, pixels);
}

